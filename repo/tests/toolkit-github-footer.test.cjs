// A fake gh holding one repository's posts.
function fakeGh(state) {
  const calls = [];
  const lines = (items) => items.map((item) => JSON.stringify(item)).join('\n') + (items.length ? '\n' : '');
  const gh = (args, input) => {
    calls.push({ args, input });
    if (args[1] === 'user') return 'me\n';
    if (args[1] === '--paginate') {
      const endpoint = args[2];
      if (/issues\/comments\?/.test(endpoint)) return lines(state.issueComments);
      if (/pulls\/comments\?/.test(endpoint)) return lines(state.reviewComments);
      if (/\/issues\?/.test(endpoint)) return lines(state.issues);
      if (/\/pulls\/(\d+)\/reviews/.test(endpoint)) return lines(state.reviews[/\/pulls\/(\d+)\//.exec(endpoint)[1]] || []);
      if (/\/pulls\?/.test(endpoint)) return lines(state.pulls);
    }
    if (args[1] === '-X') {
      if (state.failPath === args[3]) throw Object.assign(new Error('HTTP 403'), { stderr: 'HTTP 403: Forbidden\nmore' });
      const sent = JSON.parse(input).body;
      state.written[args[3]] = state.cutPath === args[3] ? sent.slice(0, -3) : sent;
      return '{}';
    }
    const endpoint = args[1];
    if (state.changedPath === endpoint && !(endpoint in state.written)) return JSON.stringify({ body: 'edited by a person' });
    return JSON.stringify({ body: endpoint in state.written ? state.written[endpoint] : stored(state)[endpoint] });
  };
  return { gh, calls };
}

// The body each post's edit path holds before any write.
function stored(state) {
  const map = {};
  for (const item of state.issueComments) map[`repos/acme/app/issues/comments/${item.id}`] = item.body;
  for (const item of state.reviewComments) map[`repos/acme/app/pulls/comments/${item.id}`] = item.body;
  for (const item of state.issues) map[`repos/acme/app/issues/${item.number}`] = item.body;
  for (const [number, reviews] of Object.entries(state.reviews)) for (const item of reviews) map[`repos/acme/app/pulls/${number}/reviews/${item.id}`] = item.body;
  return map;
}

function sampleState() {
  return {
    issueComments: [
      { id: 1, body: footed('mine'), user: 'me', html_url: 'https://github.com/acme/app/issues/7#issuecomment-1' },
      { id: 2, body: 'clean', user: 'me', html_url: 'https://github.com/acme/app/issues/7#issuecomment-2' },
      { id: 3, body: footed('theirs'), user: 'someone', html_url: 'https://github.com/acme/app/issues/7#issuecomment-3' },
    ],
    reviewComments: [
      { id: 10, body: footed('reply'), user: 'me', html_url: 'https://github.com/acme/app/pull/4#discussion_r10' },
      { id: 11, body: FOOTER, user: 'me', html_url: 'https://github.com/acme/app/pull/4#discussion_r11' },
    ],
    issues: [{ id: 20, number: 4, body: footed('pr body'), user: 'me', html_url: 'https://github.com/acme/app/pull/4' }],
    pulls: [{ id: 30, number: 4, updated_at: '2026-10-28T00:00:00Z' }, { id: 31, number: 2, updated_at: '2026-01-01T00:00:00Z' }],
    reviews: { 4: [{ id: 40, body: footed('review'), user: 'me', html_url: 'https://github.com/acme/app/pull/4#pullrequestreview-40' }], 2: [{ id: 41, body: footed('old'), user: 'me', html_url: 'https://github.com/acme/app/pull/2#pullrequestreview-41' }] },
    written: {},
  };
}

test('the sweep reports without writing unless --apply', () => {
  const state = sampleState();
  const { gh, calls } = fakeGh(state);
  const results = sweep.sweep(sweep.parseArgs(['--repo', 'acme/app']), { gh });
  assert.equal(calls.filter((call) => call.args[1] === '-X').length, 0);
  const byStatus = (status) => results.filter((row) => row.status === status).map((row) => row.url);
  assert.deepEqual(byStatus('FOUND').sort(), ['https://github.com/acme/app/issues/7#issuecomment-1', 'https://github.com/acme/app/pull/2#pullrequestreview-41', 'https://github.com/acme/app/pull/4', 'https://github.com/acme/app/pull/4#discussion_r10', 'https://github.com/acme/app/pull/4#pullrequestreview-40'].sort());
  assert.deepEqual(byStatus('SKIPPED_OTHER_AUTHOR'), ['https://github.com/acme/app/issues/7#issuecomment-3']);
  assert.deepEqual(byStatus('SKIPPED_EMPTY_AFTER_STRIP'), ['https://github.com/acme/app/pull/4#discussion_r11']);
});

test('the sweep cleans existing posts with the right method and reads each back', () => {
  const state = sampleState();
  const { gh, calls } = fakeGh(state);
  const results = sweep.sweep(sweep.parseArgs(['--repo', 'acme/app', '--apply', '--since', '2026-10-01T00:00:00Z']), { gh });
  const writes = calls.filter((call) => call.args[1] === '-X').map((call) => `${call.args[2]} ${call.args[3]}`);
  assert.deepEqual(writes, ['PATCH repos/acme/app/issues/comments/1', 'PATCH repos/acme/app/pulls/comments/10', 'PATCH repos/acme/app/issues/4', 'PUT repos/acme/app/pulls/4/reviews/40']);
  assert.equal(state.written['repos/acme/app/pulls/comments/10'], 'reply');
  assert.ok(results.filter((row) => row.status === 'CLEANED').length === 4);
  assert.ok(!results.some((row) => /pullrequestreview-41/.test(row.url || '')), '--since skips pull requests not updated in the window');
  assert.ok(calls.some((call) => call.args[2] === `repos/acme/app/issues/comments?per_page=100&since=${encodeURIComponent('2026-10-01T00:00:00.000Z')}`));
  assert.equal(sweep.exitCode(results), sweep.EXIT.FIXED);
});

test('the sweep never overwrites a post edited since the scan, and flags a stored body that differs', () => {
  const state = sampleState();
  state.changedPath = 'repos/acme/app/issues/comments/1';
  state.cutPath = 'repos/acme/app/pulls/comments/10';
  const { gh, calls } = fakeGh(state);
  const results = sweep.sweep(sweep.parseArgs(['--repo', 'acme/app', '--apply']), { gh });
  const status = (url) => results.find((row) => row.url === url).status;
  assert.equal(status('https://github.com/acme/app/issues/7#issuecomment-1'), 'SKIPPED_CHANGED');
  assert.ok(!calls.some((call) => call.args[1] === '-X' && call.args[3] === state.changedPath), 'no write to the changed post');
  assert.equal(status('https://github.com/acme/app/pull/4#discussion_r10'), 'MISMATCH');
  assert.equal(sweep.exitCode(results), sweep.EXIT.FAILED);
});

