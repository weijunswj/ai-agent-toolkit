test('the sweep exit codes: 0 clean, 3 found, 4 fixed, 1 failed', () => {
  const empty = { issueComments: [], reviewComments: [], issues: [], pulls: [], reviews: {}, written: {} };
  assert.equal(sweep.main(['--repo', 'acme/app'], { gh: fakeGh(empty).gh, stdout: () => {} }), 0);
  assert.equal(sweep.main(['--repo', 'acme/app'], { gh: fakeGh(sampleState()).gh, stdout: () => {} }), 3);
  assert.equal(sweep.main(['--repo', 'acme/app', '--apply'], { gh: fakeGh(sampleState()).gh, stdout: () => {} }), 4);
  assert.deepEqual(sweep.EXIT, { CLEAN: 0, FAILED: 1, USAGE: 2, FOUND: 3, FIXED: 4 });
});

test('the sweep reports a failed edit and exits 1; bad arguments exit 2', () => {
  const state = sampleState();
  state.failPath = 'repos/acme/app/pulls/comments/10';
  const { gh } = fakeGh(state);
  let out = '';
  assert.equal(sweep.main(['--repo', 'acme/app', '--apply'], { gh, stdout: (t) => { out += t; } }), 1);
  assert.match(out, /FAILED review_comment https:\/\/github\.com\/acme\/app\/pull\/4#discussion_r10 \(me\): HTTP 403: Forbidden\n/);
  assert.doesNotMatch(out, /more/);
  assert.match(out, /GitHub footer sweep \(apply\) of acme\/app: /);
  let err = '';
  for (const argv of [[], ['--repo', 'not a repo'], ['--repo', 'a/b', '--since', 'soon'], ['--repo', 'a/b', '--what']]) {
    assert.equal(sweep.main(argv, { stderr: (t) => { err += t; } }), 2);
  }
  assert.match(err, /Usage: node repo\/scripts\/toolkit-github-footer-sweep\.cjs/);
});

