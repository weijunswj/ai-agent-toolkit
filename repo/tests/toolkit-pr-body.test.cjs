'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const test = require('node:test');

const ROOT = path.resolve(__dirname, '..', '..');
const prBody = require('../scripts/toolkit-pr-body.cjs');

const GOOD = '## Summary\n\nDoes a thing.\n\nUAT: NOT_REQUIRED (no owner-facing change)\nBump: patch\n';
// Built from pieces so this file never holds a whole footer, link or marker itself.
const CLAUDE = ['Claude', 'Code'].join(' ');
const SESSION = ['https://claude', 'ai/code/session_abc'].join('.');
const CLOUD_FOOTER = `\n---\n_Generated by [${CLAUDE}](${SESSION})_\n`;
const AGENT_FOOTER = `\n\u{1F916} Generated with [${CLAUDE}](https://claude.com/claude-code)\n\n${SESSION}\n`;
const MARKER = `<!-- claude-projects-${'attribution'}: {"github_login":"someone"} -->\n_Requested by **Someone** · [project thread](https://claude.ai/code/project/chan_1?thread=cmsg_1)_\n\n`;

function run(body, { title = 'Fix a thing', json = true } = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pr-body-'));
  try {
    const out = path.join(dir, 'clean.md');
    const chunks = [];
    const errors = [];
    const code = prBody.main(['--body-file', '-', '--title', title, '--out', out, ...(json ? ['--json'] : [])], {
      cwd: ROOT, stdin: body, stdout: { write: (text) => chunks.push(text) }, stderr: { write: (text) => errors.push(text) },
    });
    return { code, out: fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null, report: json && chunks.length ? JSON.parse(chunks.join('')) : chunks.join(''), errors: errors.join('') };
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

// The body GOOD, padded with x's to exactly `length` characters.
const pad = (length) => GOOD.replace('Does a thing.', `Does a thing. ${'x'.repeat(length - GOOD.length - 1)}`);

// A repository's programme file (a version 2 binding) that turns governance on or off.
function writeProgramme(dir, governance) {
  const file = path.join(dir, '.github', 'toolkit-programme.json');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify({
    schema: 'toolkit.programme-binding.v2', repository: 'example-owner/example-repo', governance,
    parents: [{ issue: 7, record_prefix: 'INT-ER7-' }], store: { kind: 'github', repository: 'example-owner/TRANSPORT-example-repo', branch: 'main', path: 'state/example-owner/example-repo/' }, required_checks: ['validate'],
  }, null, 2)}\n`);
}

// The Toolkit repository's marker file, which makes the pre-flight check the Bump line.
function markToolkit(dir) {
  fs.mkdirSync(path.join(dir, 'repo', 'contracts', 'agent-rules'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'repo', 'contracts', 'agent-rules', 'global-rules.md'), '# Rules\n');
}

test('a body with every footer, link and marker comes out clean and passes', () => {
  const result = run(`${MARKER}${GOOD}${AGENT_FOOTER}${CLOUD_FOOTER}`);
  assert.equal(result.code, 0, JSON.stringify(result.report));
  assert.equal(result.out, GOOD);
  assert.deepEqual(result.report.removed.map(entry => entry.rule).sort(), ['PDG-AI-FOOTER', 'PDG-AI-FOOTER', 'PDG-AI-MARKER', 'PDG-AI-MARKER', 'PDG-AI-SESSION-LINK']);
});

test('a clean body is written back unchanged', () => {
  const result = run(GOOD);
  assert.equal(result.code, 0);
  assert.equal(result.out, GOOD);
  assert.deepEqual(result.report.removed, []);
});

test('a missing UAT line, an invalid one and a missing or doubled Bump line each block', () => {
  const cases = [
    [GOOD.replace(/^UAT:.*\n/m, ''), /no UAT line/],
    [GOOD.replace('UAT: NOT_REQUIRED (no owner-facing change)', '- UAT: NOT_REQUIRED (bulleted)'), /UAT line is invalid/],
    [GOOD.replace('Bump: patch\n', ''), /exactly one Bump: .*has 0/],
    [`${GOOD}Bump: minor\n`, /exactly one Bump: .*has 2/],
    [GOOD.replace('Bump: patch', 'Bump: tiny'), /exactly one Bump: .*has 0/],
  ];
  for (const [body, problem] of cases) {
    const result = run(body);
    assert.equal(result.code, 1, body);
    assert.ok(result.report.problems.some(line => problem.test(line)), `${body}\n${result.report.problems.join('\n')}`);
  }
});

// A body once opened over the board's pull request page budget, and was trimmed only after the board
// flagged it; the check now stops it before the pull request opens, in a governed repository only.
test('a body at or over the pull request page budget blocks in a governed repository', () => {
  const { PAGE_BUDGETS } = require('../../skills/github-program-reconciler/scripts/programme-state.cjs');
  assert.equal(prBody.PR_PAGE_BUDGET, PAGE_BUDGETS.pr, 'one budget with the board');
  const over = run(pad(prBody.PR_PAGE_BUDGET));
  assert.equal(over.report.problems.length >= 1 && over.code, 1);
  assert.ok(over.report.problems.some(line => /^the body is 3000 characters, at or over the 3000-character pull request page budget/.test(line)), over.report.problems.join('\n'));
  const under = run(pad(prBody.PR_PAGE_BUDGET - 1));
  assert.equal(under.code, 0, under.report.problems.join('\n'));
  assert.deepEqual(prBody.lineProblems(pad(prBody.PR_PAGE_BUDGET), { toolkit: true }), [], 'an ungoverned repository has no page budget');
});

// The page budget applies only where the programme file turns governance on, read as the programme sweep
// reads it: a file that turns governance off leaves the body ungoverned, the same file turned on blocks it.
test('a programme file that turns governance off does not apply the page budget', (t) => {
  const dir = freshRepo();
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const check = () => {
    const lines = [];
    const code = prBody.main(['--body-file', '-', '--title', 'Fix a thing', '--out', path.join(dir, 'clean.md'), '--json'], {
      cwd: dir, stdin: pad(prBody.PR_PAGE_BUDGET), stdout: { write: (text) => lines.push(text) }, stderr: { write() {} },
    });
    return { code, report: JSON.parse(lines.join('')) };
  };
  writeProgramme(dir, 'disabled');
  const off = check();
  assert.equal(off.code, 0, off.report.problems.join('\n'));
  assert.deepEqual(off.report.problems, []);
  writeProgramme(dir, 'enabled');
  const on = check();
  assert.equal(on.code, 1);
  assert.ok(on.report.problems.some((line) => /^the body is 3000 characters, at or over the 3000-character pull request page budget/.test(line)), on.report.problems.join('\n'));
  // A programme file saved with a leading byte order mark is read as the sweep reads it: still enabled.
  const file = path.join(dir, '.github', 'toolkit-programme.json');
  fs.writeFileSync(file, `${String.fromCharCode(0xfeff)}${fs.readFileSync(file, 'utf8')}`);
  const bom = check();
  assert.equal(bom.code, 1, bom.report.problems.join('\n'));
});

// The success line names only the checks that ran in this repository: the Bump line rule in the Toolkit
// repository, the page budget in a governed one.
test('the success line names only the checks that ran in this repository', (t) => {
  const cases = [
    [{}, 'the personal-data guard and the UAT line rule'],
    [{ toolkit: true }, 'the personal-data guard, the UAT line rule and the Bump line rule'],
    [{ governed: true }, 'the personal-data guard, the UAT line rule and the page budget'],
    [{ toolkit: true, governed: true }, 'the personal-data guard, the UAT line rule, the Bump line rule and the page budget'],
  ];
  for (const [setup, checks] of cases) {
    const dir = freshRepo();
    t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
    if (setup.toolkit) markToolkit(dir);
    if (setup.governed) writeProgramme(dir, 'enabled');
    const out = path.join(dir, 'clean.md');
    const lines = [];
    assert.equal(prBody.main(['--body-file', '-', '--title', 'Fix a thing', '--out', out], { cwd: dir, stdin: GOOD, stdout: { write: (text) => lines.push(text) }, stderr: { write() {} } }), 0, lines.join(''));
    assert.ok(lines.join('').includes(`Body ready: ${out} passes ${checks}. Write it with a route that adds no footer, then read it back.\n`), `${JSON.stringify(setup)}\n${lines.join('')}`);
  }
});

// A feature once shipped as `Bump: patch`, though the changelog rule says minor, and was only caught at
// merge. A patch line beside a fragment with an Added section is now noted, never blocked.
test('Bump: patch beside a changelog fragment with an Added section is a note, not a problem', (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'pr-body-bump-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const fragments = path.join(root, 'repo', 'docs', 'changelog.d');
  fs.mkdirSync(fragments, { recursive: true });
  fs.writeFileSync(path.join(fragments, 'README.md'), '### Added\n\n- not a fragment\n');
  fs.writeFileSync(path.join(fragments, 'claude-fix.md'), '### Fixed\n\n- a fix\n');
  assert.deepEqual(prBody.bumpNotes(GOOD, root), [], 'fixes only');
  fs.writeFileSync(path.join(fragments, 'claude-feature.md'), 'Title: a thing\n\n### Added\n\n- a new command\n');
  const [note, ...rest] = prBody.bumpNotes(GOOD, root);
  assert.deepEqual(rest, []);
  assert.match(note, /^Bump: patch, but the changelog fragment claude-feature\.md has an Added section; the changelog rule says minor/);
  assert.deepEqual(prBody.bumpNotes(GOOD.replace('Bump: patch', 'Bump: minor'), root), [], 'minor already');
});

// The pre-flight itself prints the note, in the Toolkit repository only, and still exits 0; the first
// test of it only checked that the report had a notes list.
test('the pre-flight prints the Bump note in the Toolkit repository and still passes the body', () => {
  const dir = freshRepo();
  try {
    const fragments = path.join(dir, 'repo', 'docs', 'changelog.d');
    fs.mkdirSync(fragments, { recursive: true });
    fs.writeFileSync(path.join(fragments, 'claude-feature.md'), '### Added\n\n- a new command\n');
    const out = path.join(dir, 'clean.md');
    const lines = [];
    const quiet = { cwd: dir, stdin: GOOD, stdout: { write: (text) => lines.push(text) }, stderr: { write() {} } };
    const args = ['--body-file', '-', '--title', 'Fix a thing', '--out', out];
    assert.equal(prBody.main([...args, '--json'], quiet), 0, lines.join(''));
    assert.deepEqual(JSON.parse(lines.join('')).notes, [], 'not the Toolkit repository: no note');
    fs.mkdirSync(path.join(dir, 'repo', 'contracts', 'agent-rules'), { recursive: true });
    fs.writeFileSync(path.join(dir, 'repo', 'contracts', 'agent-rules', 'global-rules.md'), '# Rules\n');
    lines.length = 0;
    assert.equal(prBody.main([...args, '--json'], quiet), 0, 'a note never blocks');
    const report = JSON.parse(lines.join(''));
    assert.equal(report.ok, true);
    assert.equal(report.notes.length, 1);
    assert.match(report.notes[0], /^Bump: patch, but the changelog fragment claude-feature\.md has an Added section/);
    lines.length = 0;
    assert.equal(prBody.main(args, quiet), 0);
    assert.match(lines.join(''), /^Body ready: [^\n]*\nNote: Bump: patch, but the changelog fragment claude-feature\.md has an Added section; [^\n]*\.\n$/m);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('an owner UAT ask needs one visible Agent UAT: PASSED line with evidence first', () => {
  const owner = extra => GOOD.replace('UAT: NOT_REQUIRED (no owner-facing change)', `UAT: OWNER_TEST_NEEDED (the owner opens the app)\n${extra}`.trimEnd());
  const asked = /owner UAT is asked before every agent step passed/;
  const refused = [
    ['', /\(has 0\)/],
    ['Agent UAT: FAILED (A2 red)', /has Agent UAT: FAILED/],
    ['Agent UAT: PENDING (A1 running)', /has Agent UAT: PENDING/],
    ['Agent UAT: PASSED', /PASSED with no evidence/],
    ['Agent UAT: PASSED (A1)\nAgent UAT: PASSED (A2)', /\(has 2\)/],
    ['<!--\nAgent UAT: PASSED (hidden)\n-->', /\(has 0\)/],
    ['```\nAgent UAT: PASSED (in code)\n```', /\(has 0\)/],
    ['Agent UAT: PASSED (   )', /PASSED with no evidence/],
  ];
  for (const [extra, why] of refused) {
    const result = run(owner(extra));
    assert.equal(result.code, 1, extra);
    const line = result.report.problems.find(problem => asked.test(problem));
    assert.ok(line && why.test(line), `${extra}\n${result.report.problems.join('\n')}`);
  }
  assert.equal(run(owner('Agent UAT: PASSED (A1 to A3 green: evidence/run-1)')).code, 0);
  // A fence closes on a run at least as long as its opening one, as GitHub renders it.
  assert.equal(run(owner('````\ncode\n`````\nAgent UAT: PASSED (A1 green)')).code, 0);
  // A long line with no closing bracket is refused in linear time.
  const started = Date.now();
  assert.equal(prBody.lineProblems(owner(`Agent UAT: PASSED (${'x '.repeat(100000)}`), { toolkit: true }).length, 1);
  assert.ok(Date.now() - started < 2000);
  // Bodies that ask the owner nothing are unaffected, with or without the line.
  assert.equal(run(GOOD).code, 0);
  assert.equal(run(GOOD.replace('NOT_REQUIRED (no owner-facing change)', "PASSED (the owner's OK)")).code, 0);
  assert.equal(run(`${GOOD}Agent UAT: FAILED (not asked)\n`).code, 0);
});

