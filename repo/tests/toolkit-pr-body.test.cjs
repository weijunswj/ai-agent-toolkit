'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const test = require('node:test');

const ROOT = path.resolve(__dirname, '..', '..');
const prBody = require('../scripts/toolkit-pr-body.cjs');

const GOOD = '## Summary\n\nDoes a thing.\n\nUAT: NOT_REQUIRED (no owner-facing change)\nBump: patch\n';
// Built from pieces so this file never holds a whole footer, link or marker itself.
const CLAUDE = ['Claude', 'Code'].join(' ');
const SESSION = ['https://claude', 'ai/code/session_abc'].join('.');
const CLOUD_FOOTER = `\n---\n_Generated by [${CLAUDE}](${SESSION})_\n`;
const AGENT_FOOTER = `\n\u{1F916} Generated with [${CLAUDE}](https://claude.com/claude-code)\n\n${SESSION}\n`;
const MARKER = `<!-- claude-projects-${'attribution'}: {"github_login":"someone"} -->\n_Requested by **Someone** · [project thread](https://claude.ai/code/project/chan_1?thread=cmsg_1)_\n\n`;

function run(body, { title = 'Fix a thing', json = true } = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pr-body-'));
  try {
    const out = path.join(dir, 'clean.md');
    const chunks = [];
    const errors = [];
    const code = prBody.main(['--body-file', '-', '--title', title, '--out', out, ...(json ? ['--json'] : [])], {
      cwd: ROOT, stdin: body, stdout: { write: (text) => chunks.push(text) }, stderr: { write: (text) => errors.push(text) },
    });
    return { code, out: fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null, report: json && chunks.length ? JSON.parse(chunks.join('')) : chunks.join(''), errors: errors.join('') };
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

test('a body with every footer, link and marker comes out clean and passes', () => {
  const result = run(`${MARKER}${GOOD}${AGENT_FOOTER}${CLOUD_FOOTER}`);
  assert.equal(result.code, 0, JSON.stringify(result.report));
  assert.equal(result.out, GOOD);
  assert.deepEqual(result.report.removed.map(entry => entry.rule).sort(), ['PDG-AI-FOOTER', 'PDG-AI-FOOTER', 'PDG-AI-MARKER', 'PDG-AI-MARKER', 'PDG-AI-SESSION-LINK']);
});

test('a clean body is written back unchanged', () => {
  const result = run(GOOD);
  assert.equal(result.code, 0);
  assert.equal(result.out, GOOD);
  assert.deepEqual(result.report.removed, []);
});

test('a missing UAT line, an invalid one and a missing or doubled Bump line each block', () => {
  const cases = [
    [GOOD.replace(/^UAT:.*\n/m, ''), /no UAT line/],
    [GOOD.replace('UAT: NOT_REQUIRED (no owner-facing change)', '- UAT: NOT_REQUIRED (bulleted)'), /UAT line is invalid/],
    [GOOD.replace('Bump: patch\n', ''), /exactly one Bump: .*has 0/],
    [`${GOOD}Bump: minor\n`, /exactly one Bump: .*has 2/],
    [GOOD.replace('Bump: patch', 'Bump: tiny'), /exactly one Bump: .*has 0/],
  ];
  for (const [body, problem] of cases) {
    const result = run(body);
    assert.equal(result.code, 1, body);
    assert.ok(result.report.problems.some(line => problem.test(line)), `${body}\n${result.report.problems.join('\n')}`);
  }
});

test('personal data the builder must fix by hand is reported, never silently removed', () => {
  const address = ['jane.tan', 'mailbox-sg.com'].join('@');
  const body = `${GOOD}Contact ${address} for details.\n`;
  const result = run(body);
  assert.equal(result.code, 1);
  assert.equal(result.out, body, 'only attribution lines are removed');
  assert.ok(result.report.problems.some(line => /pull request body:\d+:\d+ .*PDG-/.test(line)), result.report.problems.join('\n'));
  assert.ok(!result.report.problems.join('\n').includes(address), 'the value is never shown');
});

test('a session link in the title is reported: only the body is cleaned', () => {
  const titled = run(GOOD, { title: `Fix it (${SESSION})` });
  assert.equal(titled.code, 1);
  assert.ok(titled.report.problems.some(line => /pull request title/.test(line)));
});

test('bad arguments and an unreadable body exit 2 and write nothing', () => {
  const errors = [];
  const quiet = { stdout: { write() {} }, stderr: { write: (text) => errors.push(text) }, cwd: ROOT };
  assert.equal(prBody.main(['--body-file', '-', '--title', 'x'], { ...quiet, stdin: GOOD }), 2);
  assert.equal(prBody.main(['--title', 'x', '--out', 'y'], { ...quiet, stdin: GOOD }), 2);
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pr-body-'));
  try {
    const raw = path.join(dir, 'raw.md');
    fs.writeFileSync(raw, Buffer.from([0xff, 0xfe, 0x55, 0x00]));
    const out = path.join(dir, 'clean.md');
    assert.equal(prBody.main(['--body-file', raw, '--title', 'x', '--out', out], quiet), 2);
    assert.equal(fs.existsSync(out), false);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('cleanBody keeps CRLF bodies and leaves a body with no attribution byte for byte', () => {
  const crlf = GOOD.replace(/\n/g, '\r\n');
  assert.equal(prBody.cleanBody(crlf).body, crlf);
  assert.equal(prBody.cleanBody(`${crlf}\r\n---\r\n_Generated by [${CLAUDE}](https://claude.ai/code)_\r\n`).body, `${GOOD.replace(/\n/g, '\r\n').replace(/\r\n$/, '')}\n`);
});
