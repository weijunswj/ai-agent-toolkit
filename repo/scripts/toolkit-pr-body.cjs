#!/usr/bin/env node
'use strict';

// Pull request body pre-flight: the failure it prevents is a pull request that opens, or is edited,
// with a body CI or the merge check refuses (an AI footer or session link, no UAT line, no Bump
// line), which costs a full CI run and often a whole review round. Builders run it on the body
// before every pull request open or body edit, and write the body it prints, so a body that reaches
// GitHub already passes the body checks (a cloud create still gets the route's footer; the playbook's
// update right after it clears that).
//
//   node repo/scripts/toolkit-pr-body.cjs --body-file <file|-> --title <text> --out <file> [--json]
//
// It reads the body (UTF-8; "-" reads standard input), removes what Toolkit never lets into pull
// request text and what an agent or the cloud GitHub route adds on its own, writes the result to
// --out, and then checks the result the way CI and the merge check will:
//   - removed: every line that holds an AI attribution finding of the personal-data guard (a
//     "Generated with" or "Generated by" Claude Code footer, a claude.ai session, chat or
//     project-thread link, the Projects attribution marker or its requested-by line), then any rule
//     line and blank lines left dangling at the end. Nothing else is changed;
//   - checked: the personal-data guard's own `pr` mode on the title and the cleaned body (the
//     Validate personal-data job runs the same rules), with the repository's guard config or, where
//     it has none, a default with pull request text and AI attribution on (the output says which), exactly one UAT line the auto-merge check
//     accepts (toolkit-auto-merge-eligible.cjs, uatVerdict), with `UAT: OWNER_TEST_NEEDED` also
//     exactly one visible `Agent UAT: PASSED (<evidence>)` line (agent UAT runs every step a tool
//     reaches before the owner is asked; the merge check does not read this line), and, in the
//     Toolkit repository, exactly one `Bump: patch|minor|major|none` line (the merge train finder's
//     rule), and, where the repository is governed (its .github/toolkit-programme.json turns governance
//     on, read as the programme sweep reads it), a body under the programme board's pull request page
//     budget (PR_PAGE_BUDGET characters; the board raises BODY_OVER_BUDGET on a page at or over it,
//     after adding its own blocks). The success line names only the checks that ran.
// In the Toolkit repository it also prints a note, never a problem, when the body says `Bump: patch`
// while one of the branch's changelog fragments has an `### Added` section: the changelog rule says
// `minor` for a feature, a skill, a command or a new rule, and a wrong level is corrected at merge.
// It writes nothing to GitHub and reads no network. The merge scope (whether the pull request
// waits for the owner's typed merge) is not a body problem: toolkit-auto-merge-eligible.cjs
// answers that at merge time.
//
// Exit 0: the cleaned body passes every check; write it with a route that adds no footer (the
// GitHub connector's create or update call in a cloud session; see the PR review playbook).
// Exit 1: a problem the builder must fix by hand remains (each one named); the cleaned body is
// still written; a guard block whose report cannot be read counts as one. Exit 2: bad arguments, or
// the body or the guard could not be read.

const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { spawnSync } = require('node:child_process');
const { detectPrText } = require('../../skills/secure-ci-cd/scripts/personal-data-guard.cjs');
const { uatVerdict } = require('./toolkit-auto-merge-eligible.cjs');
const { validateBinding, bindingEnabled } = require('../../skills/github-program-reconciler/scripts/programme-state.cjs');

const GUARD = path.join(__dirname, '..', '..', 'skills', 'secure-ci-cd', 'scripts', 'personal-data-guard.cjs');
const ATTRIBUTION = Object.freeze(['PDG-AI-FOOTER', 'PDG-AI-SESSION-LINK', 'PDG-AI-MARKER']);
const BUMP = /^Bump: (patch|minor|major|none)[ \t]*$/gm;
const AGENT_UAT = /^Agent UAT:[ \t]*(\S+)(?:[ \t]+\((.*)\))?[ \t]*$/gm;
// Text a reader never sees: HTML comments and fenced code (closed by a run of its character at least
// as long as the opening one). An Agent UAT line there does not count.
const HIDDEN = /<!--[\s\S]*?(?:-->|$(?![\s\S]))|^ {0,3}((`|~)\2{2,})[^\n]*\n[\s\S]*?(?:^ {0,3}\1\2*[ \t]*$|$(?![\s\S]))/gm;
const RULE_LINE = /^ {0,3}(?:-{3,}|\*{3,}|_{3,})[ \t]*$/;
const TOOLKIT_MARKER = path.join('repo', 'contracts', 'agent-rules', 'global-rules.md');
const MAX_BODY_BYTES = 512 * 1024;
// The programme board's pull request page budget in characters (PAGE_BUDGETS.pr in the reconciler's
// programme-state.cjs; a test keeps the two equal). Bodies once opened over it and were trimmed later.
const PR_PAGE_BUDGET = 3000;
const PROGRAMME_FILE = path.join('.github', 'toolkit-programme.json');
const FRAGMENTS = path.join('repo', 'docs', 'changelog.d');
const REPO_CONFIG = path.join('.github', 'personal-data-guard.json');
// The guard config used where the repository has none: pull request text and AI attribution
// checked, nothing allowed. Only `pr` mode reads it, so the other scopes do not matter here.
const DEFAULT_CONFIG = Object.freeze({
  schema: 'personal-data-guard/v1',
  scope: { file_content: true, paths: true, commit_messages: true, branch_names: true, pull_request_text: true, pull_request_attribution: true },
  required_check: 'none',
});

// The body minus every line that carries an AI attribution finding, and minus the rule and blank
// lines that then dangle at its end: { body, removed: [{ line, rule }] }. Line numbers count from 1
// in the body as given.
function cleanBody(text) {
  const lines = String(text).split(/(?<=\n)/);
  const starts = [];
  let offset = 0;
  for (const line of lines) { starts.push(offset); offset += line.length; }
  const lineAt = (index) => {
    let low = 0;
    let high = starts.length - 1;
    while (low < high) {
      const mid = (low + high + 1) >> 1;
      if (starts[mid] <= index) low = mid; else high = mid - 1;
    }
    return low;
  };
  const drop = new Map();
  for (const finding of detectPrText(String(text), true)) {
    if (!ATTRIBUTION.includes(finding.rule)) continue;
    for (let at = lineAt(finding.start); at <= lineAt(Math.max(finding.start, finding.end - 1)); at += 1) {
      if (!drop.has(at)) drop.set(at, finding.rule);
    }
  }
  const removed = [...drop].sort((a, b) => a[0] - b[0]).map(([index, rule]) => ({ line: index + 1, rule }));
  const kept = lines.filter((_, index) => !drop.has(index));
  if (!drop.size) return { body: String(text), removed };
  // A footer leaves its rule line and blank lines behind; take them off the end.
  const bare = line => line.replace(/\r?\n$/, '');
  while (kept.length && (!bare(kept[kept.length - 1]).trim() || RULE_LINE.test(bare(kept[kept.length - 1])))) kept.pop();
  // An attribution header leaves blank lines at the start.
  while (kept.length && !bare(kept[0]).trim()) kept.shift();
  const body = kept.join('');
  return { body: body ? `${bare(body)}\n` : '', removed };
}

// The hand-fix problems in a cleaned body, apart from the personal-data guard's own findings.
function lineProblems(body, { toolkit, governed = false }) {
  const problems = [];
  if (governed && body.length >= PR_PAGE_BUDGET) problems.push(`the body is ${body.length} characters, at or over the ${PR_PAGE_BUDGET}-character pull request page budget the programme board checks (it adds its own blocks too): trim it to the CHANGE shape`);
  const uat = uatVerdict(body);
  if (!uat.mergeable) {
    problems.push(uat.state === 'absent'
      ? 'no UAT line: add exactly one, at the start of a line, as UAT: NOT_REQUIRED (why), UAT: OWNER_TEST_NEEDED (what the owner tries) or UAT: PASSED (the owner\'s OK)'
      : `the UAT line is invalid: ${uat.problem}`);
  }
  if (uat.state === 'OWNER_TEST_NEEDED') {
    const agent = [...body.replace(/\r\n?/g, '\n').replace(HIDDEN, '').matchAll(AGENT_UAT)];
    const why = 'owner UAT is asked before every agent step passed: run each UAT step a tool reaches (Chrome, computer use, Remote Control) first, then add exactly one line Agent UAT: PASSED (<evidence>)';
    if (agent.length !== 1) problems.push(`${why} (has ${agent.length})`);
    else if (agent[0][1] !== 'PASSED' || !agent[0][2] || !agent[0][2].trim()) problems.push(`${why} (has Agent UAT: ${agent[0][1]}${agent[0][2] && agent[0][2].trim() ? '' : ' with no evidence'})`);
  }
  if (toolkit) {
    const bumps = [...body.matchAll(BUMP)].length;
    if (bumps !== 1) problems.push(`needs exactly one Bump: patch|minor|major|none line at the start of a line (has ${bumps})`);
  }
  return problems;
}

// Notes that never block: a `Bump: patch` line beside a changelog fragment with an `### Added` section,
// which the changelog rule makes `minor` (a patch release once shipped a feature that way).
function bumpNotes(body, root) {
  const levels = [...body.matchAll(BUMP)].map(match => match[1]);
  if (levels.length !== 1 || levels[0] !== 'patch') return [];
  let names = [];
  try { names = fs.readdirSync(path.join(root, FRAGMENTS)).filter(name => name.endsWith('.md') && name !== 'README.md').sort(); } catch { return []; }
  const added = names.filter(name => {
    try { return /^### Added[ \t]*$/m.test(fs.readFileSync(path.join(root, FRAGMENTS, name), 'utf8')); } catch { return false; }
  });
  return added.length ? [`Bump: patch, but the changelog fragment ${added.join(', ')} has an Added section; the changelog rule says minor for a feature, a skill, a command or a new rule, so use Bump: minor unless those items are fixes or wording`] : [];
}

function gitRoot(cwd) {
  const run = spawnSync('git', ['rev-parse', '--show-toplevel'], { cwd, encoding: 'utf8', windowsHide: true });
  return run.status === 0 ? run.stdout.trim() : null;
}

// Whether the programme file turns governance on, read as the programme sweep reads it (validateBinding,
// then bindingEnabled, as loadBinding does). A missing, unreadable, invalid or switched-off file is not
// governed, so the page budget applies only where the board checks it.
function programmeGoverned(root) {
  const file = path.join(root, PROGRAMME_FILE);
  if (!fs.existsSync(file)) return false;
  try {
    const text = fs.readFileSync(file, 'utf8');
    return bindingEnabled(validateBinding(JSON.parse(text.charCodeAt(0) === 0xfeff ? text.slice(1) : text)));
  } catch { return false; }
}

// Words as a plain list: "a", "a and b", "a, b and c".
const joinWords = words => (words.length > 1 ? `${words.slice(0, -1).join(', ')} and ${words[words.length - 1]}` : words.join(''));

// The personal-data guard's `pr` mode on the title and body, with the repository's own guard
// config, or DEFAULT_CONFIG where it has none: { code, findings: [lines], unread, config }. A block
// whose finding lines cannot be read is `unread`, never a pass.
function guardFindings(root, title, body, guard) {
  const own = fs.existsSync(path.join(root, REPO_CONFIG));
  const temp = own ? null : fs.mkdtempSync(path.join(os.tmpdir(), 'toolkit-pr-body-'));
  try {
    const args = [guard, 'pr', '--repo', root];
    if (temp) {
      const file = path.join(temp, 'personal-data-guard.json');
      fs.writeFileSync(file, `${JSON.stringify(DEFAULT_CONFIG, null, 2)}\n`);
      args.push('--config', file);
    }
    const run = spawnSync(process.execPath, args, {
      cwd: root, encoding: 'utf8', windowsHide: true, env: { ...process.env, PDG_PR_TITLE: title, PDG_PR_BODY: body },
    });
    const config = own ? 'repository' : 'default';
    if (run.error || ![0, 1].includes(run.status)) return { code: 2, findings: [], config };
    const findings = String(run.stderr || '').split(/\r?\n/).filter(line => /^ {2}pull request (?:title|body)\S*\s/.test(line)).map(line => line.trim());
    return { code: run.status, findings, unread: run.status === 1 && !findings.length, config };
  } finally {
    if (temp) fs.rmSync(temp, { recursive: true, force: true });
  }
}

function readBody(file, cwd, stdin) {
  try {
    const raw = file === '-' ? (stdin === undefined ? fs.readFileSync(0) : Buffer.from(String(stdin), 'utf8')) : fs.readFileSync(path.resolve(cwd, file));
    if (raw.length > MAX_BODY_BYTES) return null;
    const text = new TextDecoder('utf-8', { fatal: true, ignoreBOM: false }).decode(raw);
    return text.includes('\u0000') ? null : text;
  } catch { return null; }
}

const USAGE = 'Usage: node repo/scripts/toolkit-pr-body.cjs --body-file <file|-> --title <text> --out <file> [--json]\n'
  + 'Removes AI footers, session links and attribution lines, writes the cleaned body to --out, then checks it\n'
  + 'with the personal-data guard, the UAT line rule, (in the Toolkit repository) the one-Bump-line rule and (in a\n'
  + 'governed repository) the 3,000-character pull request page budget. In the Toolkit repository it also notes\n'
  + 'Bump: patch beside a changelog fragment with an Added section; a note never fails the body.\n';

function main(argv, { cwd = process.cwd(), stdout = process.stdout, stderr = process.stderr, stdin, guard: guardScript = GUARD } = {}) {
  const value = (name) => { const at = argv.indexOf(name); return at >= 0 && at + 1 < argv.length ? argv[at + 1] : undefined; };
  const bodyFile = value('--body-file');
  const title = value('--title');
  const out = value('--out');
  const json = argv.includes('--json');
  if (!bodyFile || title === undefined || !out || (bodyFile !== '-' && bodyFile.startsWith('--')) || out.startsWith('--')) { stderr.write(USAGE); return 2; }
  const root = gitRoot(cwd);
  if (!root) { stderr.write('Run it from inside the repository the pull request is for.\n'); return 2; }
  const text = readBody(bodyFile, cwd, stdin);
  if (text === null) { stderr.write('The body could not be read as UTF-8 text (missing, over 512 KB, or another encoding). Save it as UTF-8 or pipe it in with --body-file -.\n'); return 2; }
  const { body, removed } = cleanBody(text);
  try { fs.writeFileSync(path.resolve(cwd, out), body); } catch (error) { stderr.write(`The cleaned body could not be written to ${out}: ${error.code || error.message}\n`); return 2; }
  const guard = guardFindings(root, title, body, guardScript);
  if (guard.code === 2) { stderr.write('The personal-data guard could not scan the title and body, so the body is not known to pass. Run it from the repository folder with a readable guard config.\n'); return 2; }
  const toolkit = fs.existsSync(path.join(root, TOOLKIT_MARKER));
  const governed = programmeGoverned(root);
  const problems = [
    ...lineProblems(body, { toolkit, governed }),
    ...guard.findings.map(finding => `the personal-data guard blocks ${finding} (place, class, rule): edit that line`),
    ...(guard.unread ? ['the personal-data guard blocked the title or body, but its report could not be read: run its pr mode directly to see why'] : []),
  ];
  const ok = problems.length === 0;
  const notes = toolkit ? bumpNotes(body, root) : [];
  const checked = ['the personal-data guard', 'the UAT line rule', ...(toolkit ? ['the Bump line rule'] : []), ...(governed ? ['the page budget'] : [])];
  if (json) {
    stdout.write(`${JSON.stringify({ ok, out, removed, problems, notes, guard_config: guard.config }, null, 2)}\n`);
  } else {
    const lines = [];
    if (guard.config === 'default') lines.push(`This repository has no ${REPO_CONFIG.split(path.sep).join('/')}, so the guard ran with the pre-flight's default (pull request text and AI attribution on).`);
    if (removed.length) lines.push(`Removed ${removed.length} line(s): ${removed.map(entry => `line ${entry.line} (${entry.rule})`).join(', ')}.`);
    lines.push(ok
      ? `Body ready: ${out} passes ${joinWords(checked)}. Write it with a route that adds no footer, then read it back.`
      : `Body not ready (${out} holds the cleaned body); fix by hand:\n${problems.map(problem => `- ${problem}`).join('\n')}`);
    for (const note of notes) lines.push(`Note: ${note}.`);
    stdout.write(`${lines.join('\n')}\n`);
  }
  return ok ? 0 : 1;
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = Object.freeze({ cleanBody, lineProblems, bumpNotes, main, PR_PAGE_BUDGET });
